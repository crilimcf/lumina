async function ios() {
  const root = path.join(mobileRoot, 'ios');
  const plistPath = path.join(root, 'App/App/Info.plist');
  if (!await exists(plistPath)) throw new Error('iOS project has not been generated by Capacitor.');

  let plist = await read(plistPath);
  const stringKeys = {
    NSCameraUsageDescription:'A Lumina usa a câmara quando escolhes tirar uma fotografia, gravar vídeo ou iniciar uma videochamada.',
    NSMicrophoneUsageDescription:'A Lumina usa o microfone em chamadas, vídeos e transmissões iniciadas por ti.',
    NSPhotoLibraryUsageDescription:'A Lumina acede às fotografias e vídeos apenas quando escolhes conteúdo para partilhar.',
    NSPhotoLibraryAddUsageDescription:'A Lumina pode guardar uma fotografia no dispositivo quando pedes explicitamente para a guardar.',
    NSLocationWhenInUseUsageDescription:'A localização é usada apenas quando pedes experiências locais no Lumina One.',
  };
  for (const [key, value] of Object.entries(stringKeys)) {
    if (!plist.includes(`<key>${key}</key>`)) plist = insertBefore(plist, '</dict>', `\t<key>${key}</key>\n\t<string>${value}</string>\n`);
  }
  if (!plist.includes('<string>lumina</string>')) {
    plist = insertBefore(plist, '</dict>', `\t<key>CFBundleURLTypes</key>\n\t<array>\n\t\t<dict>\n\t\t\t<key>CFBundleURLName</key>\n\t\t\t<string>${APP_ID}</string>\n\t\t\t<key>CFBundleURLSchemes</key>\n\t\t\t<array><string>lumina</string></array>\n\t\t</dict>\n\t</array>\n`);
  }
  if (!plist.includes('<key>UIBackgroundModes</key>')) {
    plist = insertBefore(plist, '</dict>', '\t<key>UIBackgroundModes</key>\n\t<array><string>remote-notification</string></array>\n');
  }
  await write(plistPath, plist);

  const entitlementsPath = path.join(root, 'App/App/App.entitlements');
  await write(entitlementsPath, `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0">\n<dict>\n\t<key>aps-environment</key>\n\t<string>production</string>\n</dict>\n</plist>\n`);

  const projectPath = path.join(root, 'App/App.xcodeproj/project.pbxproj');
  if (await exists(projectPath)) {
    let project = await read(projectPath);
    project = project.replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${VERSION};`);
    project = project.replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${BUILD};`);
    if (!project.includes('CODE_SIGN_ENTITLEMENTS = App/App.entitlements;')) {
      project = project.replace(/CODE_SIGN_STYLE = Automatic;/g, 'CODE_SIGN_ENTITLEMENTS = App/App.entitlements;\n\t\t\t\tCODE_SIGN_STYLE = Automatic;');
    }
    await write(projectPath, project);
  }

  const appIcon = path.join(root, 'App/App/Assets.xcassets/AppIcon.appiconset');
  await fs.mkdir(appIcon, { recursive:true });
  const images = [];
  for (const [filename, pixels, size, scale, idiom] of iosIcons) {
    await sharp(iconSource).resize(pixels, pixels, { fit:'cover' }).png().toFile(path.join(appIcon, filename));
    images.push({ filename, idiom, scale, size });
  }
  await write(path.join(appIcon, 'Contents.json'), JSON.stringify({ images, info:{ author:'xcode', version:1 } }, null, 2));

  console.log(`[mobile] iOS configured: ${APP_ID} ${VERSION} (${BUILD}) with native permissions, push entitlement and deep link.`);
}

if (platform === 'android') await android();
else await ios();
